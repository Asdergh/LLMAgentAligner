"""
Проверка offline-инференса vLLM на маленькой русскоязычной модели.
Три промпта разной длины (~10, ~50, ~100 слов) — смотрим, как модель
справляется с генерацией при разной длине контекста на входе.

Установка (на VM с NVIDIA GPU):
    pip install vllm

Запуск:
    python vllm_context_test.py
"""

from vllm import LLM, SamplingParams
import time

MODEL_NAME = "Qwen/Qwen2.5-0.5B-Instruct"  # самая маленькая модель с приличным русским
# Альтернатива, если качества 0.5B не хватит:
# MODEL_NAME = "Qwen/Qwen2.5-1.5B-Instruct"

# --- Три промпта возрастающей длины ---

prompt_short = (
    "Объясни, что такое машинное обучение, простыми словами за два предложения."
)  # ~10 слов

prompt_medium = (
    "Ты — ассистент технической поддержки в компании, которая занимается облачными "
    "сервисами. Клиент написал, что у него не получается подключиться к серверу "
    "уже второй день, и он злится. Напиши вежливый и структурированный ответ, "
    "который включает извинение, уточняющий вопрос про код ошибки и предложение "
    "по временному решению проблемы, пока инженеры разбираются в причине."
)  # ~50 слов

prompt_long = (
    "Представь, что ты пишешь техническую документацию для внутреннего сервиса "
    "компании, который занимается развертыванием и обслуживанием больших языковых "
    "моделей на собственной инфраструктуре. Сервис использует библиотеку vLLM для "
    "инференса, поддерживает несколько параллельных пользователей одновременно, "
    "и модели могут быть дообучены под конкретные задачи компании с помощью LoRA-адаптеров. "
    "Опиши в трёх пунктах, какие шаги нужно предусмотреть при проектировании такого сервиса, "
    "чтобы он был отказоустойчивым, эффективно использовал видеопамять GPU и позволял "
    "быстро подключать новые дообученные модели без простоя основного сервиса. "
    "Ответ должен быть структурированным и практичным, ориентированным на инженерную команду, "
    "которая будет заниматься реализацией и поддержкой этого решения в проде."
)  # ~100 слов


prompts = [
    ("SHORT (~10 слов)", prompt_short),
    ("MEDIUM (~50 слов)", prompt_medium),
    ("LONG (~100 слов)", prompt_long),
]

sampling_params = SamplingParams(
    temperature=0.7,
    top_p=0.9,
    max_tokens=300,  # даём модели достаточно места для полного ответа
)

print(f"Загрузка модели: {MODEL_NAME}\n")
llm = LLM(model=MODEL_NAME, max_model_len=4096)

for label, prompt in prompts:
    word_count = len(prompt.split())
    print("=" * 80)
    print(f"{label} | слов во входе: {word_count}")
    print("-" * 80)

    start = time.time()
    output = llm.generate([prompt], sampling_params)[0]
    elapsed = time.time() - start

    input_tokens = len(output.prompt_token_ids)
    output_tokens = len(output.outputs[0].token_ids)

    print(f"Промпт: {prompt}\n")
    print(f"Ответ модели:\n{output.outputs[0].text.strip()}\n")
    print(
        f"[Токенов на входе: {input_tokens} | "
        f"Токенов на выходе: {output_tokens} | "
        f"Время генерации: {elapsed:.2f} сек | "
        f"Скорость: {output_tokens / elapsed:.1f} ток/сек]"
    )
    print()

print("=" * 80)
print(
    "Оценка контекста: сравни качество и связность ответов между SHORT/MEDIUM/LONG.\n"
    "Если на LONG промпте модель теряет нить рассуждения, путает пункты задания\n"
    "или отвечает менее релевантно — это признак того, что для такой длины входа\n"
    "модели 0.5B не хватает 'внимания' к деталям, и стоит попробовать модель покрупнее\n"
    "(например, Qwen2.5-1.5B или Qwen2.5-3B-Instruct)."
)